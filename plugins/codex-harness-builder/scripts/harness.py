#!/usr/bin/env python3
"""Codex Harness Builder.

A dependency-free, non-destructive project analyzer and harness generator.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Iterable

VERSION = "0.1.0"
HTML_START = "<!-- CODEX-HARNESS:START -->"
HTML_END = "<!-- CODEX-HARNESS:END -->"
TOML_START = "# CODEX-HARNESS:START"
TOML_END = "# CODEX-HARNESS:END"
GENERATED_SENTINEL = "# Generated by Codex Harness Builder"

IGNORE_DIRS = {
    ".git", ".hg", ".svn", ".idea", ".vscode", ".next", ".nuxt", ".turbo",
    "node_modules", "vendor", "dist", "build", "target", "coverage", ".coverage",
    ".venv", "venv", "env", "__pycache__", ".pytest_cache", ".mypy_cache",
    ".ruff_cache", ".gradle", ".cache", "Pods", "DerivedData",
}
SOURCE_EXTS = {
    ".py", ".js", ".jsx", ".ts", ".tsx", ".php", ".go", ".rs", ".java", ".kt",
    ".kts", ".cs", ".cpp", ".cc", ".c", ".h", ".hpp", ".rb", ".swift", ".dart",
    ".vue", ".svelte", ".sql", ".sh", ".ps1",
}
TEST_PATTERNS = (
    re.compile(r"(^|/)(tests?|specs?)(/|$)", re.I),
    re.compile(r"(^|/).*(_test|\.test|\.spec)\.[^/]+$", re.I),
)
SECRET_PATTERNS = [
    re.compile(r"(?i)(api[_-]?key|secret|password|passwd|access[_-]?token)\s*[:=]\s*\S{8,}"),
    re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
    re.compile(r"\bgh[pousr]_[A-Za-z0-9_]{20,}\b"),
    re.compile(r"\bsk-[A-Za-z0-9_-]{20,}\b"),
]


@dataclass
class Analysis:
    project: str
    name: str
    stacks: list[str]
    frameworks: list[str]
    source_files: int
    test_files: int
    config_files: list[str]
    docs: list[str]
    monorepo_signals: list[str]
    complexity: str
    score: int
    suggested_agents: list[str]


def iter_project_files(root: Path, max_files: int = 12000) -> Iterable[Path]:
    count = 0
    for current, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in IGNORE_DIRS and not d.startswith(".codex-harness-cache")]
        cur = Path(current)
        for name in files:
            if count >= max_files:
                return
            count += 1
            yield cur / name


def rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def detect(root: Path) -> Analysis:
    files = list(iter_project_files(root))
    rels = {rel(p, root): p for p in files}
    names = set(rels)

    stacks: list[str] = []
    frameworks: list[str] = []
    config: list[str] = []
    docs: list[str] = []
    mono: list[str] = []

    def present(path: str) -> bool:
        return path in names

    manifests = {
        "package.json": "Node.js/JavaScript",
        "composer.json": "PHP",
        "pyproject.toml": "Python",
        "requirements.txt": "Python",
        "Pipfile": "Python",
        "go.mod": "Go",
        "Cargo.toml": "Rust",
        "pom.xml": "Java",
        "build.gradle": "Java/Kotlin",
        "build.gradle.kts": "Kotlin",
        "Gemfile": "Ruby",
        "pubspec.yaml": "Dart/Flutter",
    }
    for filename, stack in manifests.items():
        if present(filename):
            config.append(filename)
            if stack not in stacks:
                stacks.append(stack)

    if present("package.json"):
        try:
            pkg = json.loads(rels["package.json"].read_text(encoding="utf-8", errors="ignore"))
            deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
            candidates = {
                "react": "React", "next": "Next.js", "vue": "Vue", "nuxt": "Nuxt",
                "svelte": "Svelte", "express": "Express", "fastify": "Fastify",
                "@nestjs/core": "NestJS", "vite": "Vite",
            }
            for dep, label in candidates.items():
                if dep in deps and label not in frameworks:
                    frameworks.append(label)
            if "workspaces" in pkg:
                mono.append("package.json workspaces")
        except Exception:
            pass

    if present("composer.json"):
        try:
            comp = json.loads(rels["composer.json"].read_text(encoding="utf-8", errors="ignore"))
            req = {**comp.get("require", {}), **comp.get("require-dev", {})}
            for dep, label in {
                "laravel/framework": "Laravel", "symfony/framework-bundle": "Symfony"
            }.items():
                if dep in req and label not in frameworks:
                    frameworks.append(label)
        except Exception:
            pass

    for marker, label in {
        "manage.py": "Django",
        "artisan": "Laravel",
        "docker-compose.yml": "Docker Compose",
        "docker-compose.yaml": "Docker Compose",
        "compose.yml": "Docker Compose",
        "compose.yaml": "Docker Compose",
        "Dockerfile": "Docker",
    }.items():
        if present(marker):
            if marker not in config:
                config.append(marker)
            if label not in frameworks:
                frameworks.append(label)

    for path in names:
        lower = path.lower()
        base = Path(path).name.lower()
        if base in {"readme.md", "architecture.md", "contributing.md", "prd.md", "design.md"} or lower.startswith("docs/"):
            if len(docs) < 30:
                docs.append(path)
        if lower in {"pnpm-workspace.yaml", "lerna.json", "nx.json", "turbo.json"}:
            mono.append(path)
        if lower.endswith(".sln") and "C#/.NET" not in stacks:
            stacks.append("C#/.NET")

    source_files = 0
    test_files = 0
    ext_counts: dict[str, int] = {}
    for path in names:
        ext = Path(path).suffix.lower()
        if ext in SOURCE_EXTS:
            source_files += 1
            ext_counts[ext] = ext_counts.get(ext, 0) + 1
            if any(p.search(path) for p in TEST_PATTERNS):
                test_files += 1

    ext_stack = {
        ".py": "Python", ".php": "PHP", ".go": "Go", ".rs": "Rust", ".rb": "Ruby",
        ".java": "Java", ".kt": "Kotlin", ".kts": "Kotlin", ".cs": "C#/.NET",
        ".dart": "Dart/Flutter", ".swift": "Swift",
        ".js": "JavaScript", ".jsx": "JavaScript", ".ts": "TypeScript", ".tsx": "TypeScript",
    }
    for ext, count in sorted(ext_counts.items(), key=lambda x: x[1], reverse=True):
        label = ext_stack.get(ext)
        if label and count >= 2 and label not in stacks:
            stacks.append(label)

    score = 0
    score += min(source_files // 40, 8)
    score += max(0, len(stacks) - 1)
    score += min(len(frameworks) // 2, 3)
    score += 3 if mono else 0
    score += 2 if any("Docker Compose" == f for f in frameworks) else 0
    score += 1 if test_files >= 10 else 0

    if source_files <= 30 and score <= 2:
        complexity = "SMALL"
        agents: list[str] = []
    elif source_files > 350 or score >= 9 or mono:
        complexity = "LARGE"
        agents = ["architect", "researcher", "developer", "tester", "reviewer"]
    else:
        complexity = "MEDIUM"
        agents = ["researcher", "developer", "tester", "reviewer"]

    return Analysis(
        project=str(root),
        name=root.name,
        stacks=stacks or ["Unknown/mixed"],
        frameworks=frameworks,
        source_files=source_files,
        test_files=test_files,
        config_files=sorted(config),
        docs=sorted(docs),
        monorepo_signals=sorted(set(mono)),
        complexity=complexity,
        score=score,
        suggested_agents=agents,
    )


def replace_managed(text: str, block: str, start: str, end: str) -> str:
    managed = f"{start}\n{block.rstrip()}\n{end}"
    if start in text and end in text:
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
        return pattern.sub(managed, text, count=1)
    base = text.rstrip()
    return (base + "\n\n" if base else "") + managed + "\n"


def write_managed(path: Path, block: str, start: str, end: str, dry_run: bool) -> str:
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    new = replace_managed(old, block, start, end)
    if new == old:
        return "unchanged"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8")
    return "updated" if old else "created"


def write_owned(path: Path, content: str, dry_run: bool) -> str:
    if path.exists():
        old = path.read_text(encoding="utf-8", errors="ignore")
        if GENERATED_SENTINEL not in old:
            return "conflict"
        if old == content:
            return "unchanged"
        status = "updated"
    else:
        status = "created"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return status


def role_config(role: str) -> str:
    roles = {
        "architect": (
            "medium",
            "Design complex changes before implementation. Inspect only the code needed to understand boundaries, contracts, data flow, and migration risk. Produce a concise implementation plan. Do not perform broad refactors unless explicitly required."
        ),
        "researcher": (
            "low",
            "Locate the smallest set of files, symbols, tests, and docs relevant to the assigned question. Prefer search and targeted reads over broad repository scans. Return paths, evidence, and a concise recommendation; do not edit files unless explicitly asked."
        ),
        "developer": (
            "low",
            "Implement the assigned scoped change with minimal edits. Preserve existing APIs and conventions unless the task explicitly changes them. Avoid unrelated refactors, formatting churn, new dependencies, and broad context reads."
        ),
        "tester": (
            "low",
            "Validate the assigned change with the narrowest meaningful tests first. Add or adjust focused tests when needed. Report exact failures and likely causes. Do not change production code unless explicitly delegated."
        ),
        "reviewer": (
            "medium",
            "Review completed changes against the request, existing contracts, regression risk, security basics, and maintainability. Focus on concrete defects and missed requirements. Avoid style-only commentary unless it affects correctness."
        ),
    }
    effort, instructions = roles[role]
    return (
        f"{GENERATED_SENTINEL} v{VERSION}\n"
        f"model_reasoning_effort = \"{effort}\"\n"
        "developer_instructions = \"\"\"\n"
        f"{instructions}\n"
        "\"\"\"\n"
    )


def agents_block(analysis: Analysis) -> str:
    if not analysis.suggested_agents:
        return "# Small project: custom subagents intentionally omitted to reduce context and orchestration overhead."
    desc = {
        "architect": "Plan architecture and implementation for complex, cross-cutting changes.",
        "researcher": "Find the minimum relevant code, tests, and docs before implementation.",
        "developer": "Implement scoped code changes with minimal unrelated edits.",
        "tester": "Run focused tests and investigate regressions.",
        "reviewer": "Review completed changes for correctness, regressions, and missed requirements.",
    }
    lines = ["[agents]", "enabled = true", ""]
    for role in analysis.suggested_agents:
        lines += [
            f"[agents.{role}]",
            f'description = "{desc[role]}"',
            f'config_file = "agents/{role}.toml"',
            "",
        ]
    return "\n".join(lines).rstrip()


def agents_md_block(analysis: Analysis) -> str:
    stack = ", ".join(analysis.stacks)
    frameworks = ", ".join(analysis.frameworks) if analysis.frameworks else "none detected"
    return f"""# Codex project harness

Project profile: **{analysis.complexity}** | Stack: {stack} | Frameworks: {frameworks}

## Working rules
- Start from the user's requested scope. Locate relevant files before reading broad directories.
- Do not read the full repository, long PRDs, or all project-context files by default.
- For simple dependent work, stay in the main agent. Use subagents only when specialization or independent parallel work has clear value.
- Give each subagent only the files, requirements, constraints, and acceptance criteria it needs.
- Preserve existing APIs, schemas, dependencies, and conventions unless the task explicitly requires changing them.
- Avoid unrelated refactors, formatting churn, and speculative cleanup.
- Run the narrowest meaningful tests first; expand only when results or risk justify it.
- Keep completion reports concise: changed files, key change, tests, and any remaining risk.

## Durable project knowledge
- `.project-context/PROJECT.md`: stable project facts and entry points.
- `.project-context/ARCHITECTURE.md`: current architecture, not future wishes.
- `.project-context/DECISIONS.md`: lasting design decisions with rationale.
- `.project-context/MEMORY.md`: only small, stable facts that materially help future work.
- `.project-context/LESSONS.md`: reusable failure/solution patterns.
- `.project-context/TODO.md`: current project work, not chat history.
- Never store passwords, private keys, API keys, access tokens, credentials, or other secrets in these files.

## Complexity policy
- SIMPLE: solve directly; no planning file and usually no subagents.
- NORMAL: targeted research -> implementation -> focused tests; reviewer only when risk warrants it.
- COMPLEX: architecture/plan -> targeted research -> implementation -> tests -> review. Use `.agent/plans/` for durable execution plans only when the change is genuinely cross-cutting.
"""


def context_file(title: str, body: str) -> str:
    return f"{GENERATED_SENTINEL} v{VERSION}\n\n# {title}\n\n{body.rstrip()}\n"


def project_context(analysis: Analysis) -> dict[str, str]:
    return {
        "PROJECT.md": context_file(
            "Project",
            f"""## Snapshot
- Name: `{analysis.name}`
- Complexity: `{analysis.complexity}`
- Detected stack: {', '.join(analysis.stacks)}
- Detected frameworks/tools: {', '.join(analysis.frameworks) if analysis.frameworks else 'none detected'}
- Source files counted: {analysis.source_files}
- Test-like source files counted: {analysis.test_files}

## Stable facts
Add only facts expected to remain useful across many development sessions.

## Entry points
Add important runtime, build, test, and deployment entry points as they become known.
"""
        ),
        "ARCHITECTURE.md": context_file(
            "Architecture",
            """Describe the architecture that exists today. Keep this concise and evidence-based.\n\n## Components\n\n## Data flow\n\n## External boundaries\n"""
        ),
        "DECISIONS.md": context_file(
            "Decisions",
            """Record only decisions that future work should preserve.\n\nTemplate:\n\n## YYYY-MM-DD — Decision title\n- Decision:\n- Rationale:\n- Alternatives rejected:\n- Consequences:\n"""
        ),
        "MEMORY.md": context_file(
            "Project Memory",
            """Keep this intentionally small. Store stable project constraints, compatibility requirements, and non-secret facts only.\n\nDo not store credentials, tokens, passwords, private keys, or temporary debugging details.\n"""
        ),
        "LESSONS.md": context_file(
            "Reusable Lessons",
            """Record recurring implementation or debugging patterns only when they are likely to prevent future wasted work.\n\nTemplate:\n\n## Pattern\n- Symptom:\n- Cause:\n- Solution:\n- Reuse when:\n"""
        ),
        "TODO.md": context_file(
            "Current Work",
            """Keep only active or near-term project work here. Do not copy the conversation transcript.\n\n- [ ]\n"""
        ),
    }


def plan_file() -> str:
    return context_file(
        "Execution Plans",
        """Create a plan in `.agent/plans/` only for genuinely complex changes: cross-module work, migrations, contract changes, or risky multi-step implementations.\n\nA plan should contain: goal, current evidence, affected areas, steps, tests, migration/rollback notes, and completion criteria.\n"""
    )


def build(root: Path, dry_run: bool, update: bool = False) -> dict:
    analysis = detect(root)
    changes: dict[str, str] = {}

    changes["AGENTS.md"] = write_managed(root / "AGENTS.md", agents_md_block(analysis), HTML_START, HTML_END, dry_run)
    changes[".codex/config.toml"] = write_managed(root / ".codex/config.toml", agents_block(analysis), TOML_START, TOML_END, dry_run)

    desired_agents = set(analysis.suggested_agents)
    for role in sorted(desired_agents):
        p = root / ".codex" / "agents" / f"{role}.toml"
        changes[rel(p, root)] = write_owned(p, role_config(role), dry_run)

    for name, content in project_context(analysis).items():
        p = root / ".project-context" / name
        if p.exists():
            changes[rel(p, root)] = "preserved"
        else:
            changes[rel(p, root)] = write_owned(p, content, dry_run)

    if analysis.complexity == "LARGE":
        p = root / ".agent" / "PLANS.md"
        changes[rel(p, root)] = write_owned(p, plan_file(), dry_run) if not p.exists() else "preserved"
        keep = root / ".agent" / "plans" / ".gitkeep"
        if keep.exists():
            changes[rel(keep, root)] = "unchanged"
        else:
            if not dry_run:
                keep.parent.mkdir(parents=True, exist_ok=True)
                keep.write_text("", encoding="utf-8")
            changes[rel(keep, root)] = "created"

    conflicts = [p for p, s in changes.items() if s == "conflict"]
    return {
        "version": VERSION,
        "mode": "update" if update else "init",
        "dry_run": dry_run,
        "analysis": asdict(analysis),
        "changes": changes,
        "conflicts": conflicts,
    }


def file_line_count(path: Path) -> int:
    try:
        return len(path.read_text(encoding="utf-8", errors="ignore").splitlines())
    except OSError:
        return 0


def audit(root: Path) -> dict:
    analysis = detect(root)
    findings: list[dict[str, str]] = []

    def add(level: str, code: str, message: str):
        findings.append({"level": level, "code": code, "message": message})

    agents = root / "AGENTS.md"
    if not agents.exists():
        add("warning", "missing_agents", "AGENTS.md is missing.")
    else:
        lines = file_line_count(agents)
        if lines > 220:
            add("warning", "agents_bloat", f"AGENTS.md has {lines} lines; consider keeping core instructions smaller.")
        text = agents.read_text(encoding="utf-8", errors="ignore")
        if text.count(HTML_START) > 1 or text.count(HTML_END) > 1:
            add("error", "duplicate_agents_blocks", "AGENTS.md contains duplicate harness managed markers.")

    cfg = root / ".codex" / "config.toml"
    if analysis.suggested_agents and not cfg.exists():
        add("warning", "missing_codex_config", "Custom agents are suggested but .codex/config.toml is missing.")
    if cfg.exists():
        text = cfg.read_text(encoding="utf-8", errors="ignore")
        if text.count(TOML_START) > 1 or text.count(TOML_END) > 1:
            add("error", "duplicate_config_blocks", ".codex/config.toml contains duplicate harness managed markers.")

    for role in analysis.suggested_agents:
        p = root / ".codex" / "agents" / f"{role}.toml"
        if not p.exists():
            add("warning", "missing_agent_role", f"Expected custom agent role is missing: {rel(p, root)}")

    memory = root / ".project-context" / "MEMORY.md"
    if memory.exists():
        lines = file_line_count(memory)
        if lines > 160:
            add("warning", "memory_bloat", f"MEMORY.md has {lines} lines; stable memory should stay intentionally small.")
        text = memory.read_text(encoding="utf-8", errors="ignore")
        for pat in SECRET_PATTERNS:
            if pat.search(text):
                add("error", "possible_secret", "MEMORY.md appears to contain secret-like material. Remove it and rotate any real credential.")
                break

    ctx = root / ".project-context"
    for name in ["PROJECT.md", "ARCHITECTURE.md", "DECISIONS.md", "MEMORY.md", "LESSONS.md", "TODO.md"]:
        if not (ctx / name).exists():
            add("info", "missing_context", f"Optional project context file is missing: .project-context/{name}")

    if analysis.complexity == "SMALL":
        role_dir = root / ".codex" / "agents"
        if role_dir.exists():
            count = len(list(role_dir.glob("*.toml")))
            if count >= 4:
                add("warning", "too_many_agents", f"Small project has {count} custom agent roles; this may add unnecessary orchestration overhead.")

    severity = {"error": 3, "warning": 2, "info": 1}
    findings.sort(key=lambda x: severity[x["level"]], reverse=True)
    return {
        "version": VERSION,
        "analysis": asdict(analysis),
        "status": "error" if any(f["level"] == "error" for f in findings) else "warning" if any(f["level"] == "warning" for f in findings) else "ok",
        "findings": findings,
    }


def normalize_managed_file(path: Path, dry_run: bool) -> str:
    if not path.exists():
        return "missing"
    old = path.read_text(encoding="utf-8", errors="ignore")
    lines = [line.rstrip() for line in old.splitlines()]
    out: list[str] = []
    blanks = 0
    for line in lines:
        if line == "":
            blanks += 1
            if blanks > 2:
                continue
        else:
            blanks = 0
        out.append(line)
    new = "\n".join(out).rstrip() + "\n"
    if new == old:
        return "unchanged"
    if not dry_run:
        path.write_text(new, encoding="utf-8")
    return "updated"


def compact(root: Path, dry_run: bool) -> dict:
    paths = [root / "AGENTS.md", root / ".codex" / "config.toml"]
    paths.extend((root / ".project-context").glob("*.md") if (root / ".project-context").exists() else [])
    changes = {rel(p, root): normalize_managed_file(p, dry_run) for p in paths}
    return {
        "version": VERSION,
        "dry_run": dry_run,
        "changes": changes,
        "note": "Safe compaction only normalized trailing whitespace and repeated blank lines; it did not summarize or delete project knowledge.",
    }


def stable_hash(data: object) -> str:
    raw = json.dumps(data, sort_keys=True, ensure_ascii=False).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:12]


def human_analysis(a: Analysis) -> str:
    lines = [
        f"Project: {a.name}",
        f"Complexity: {a.complexity} (score={a.score})",
        f"Stack: {', '.join(a.stacks)}",
        f"Frameworks/tools: {', '.join(a.frameworks) if a.frameworks else 'none detected'}",
        f"Source files: {a.source_files}",
        f"Test-like files: {a.test_files}",
        f"Suggested agents: {', '.join(a.suggested_agents) if a.suggested_agents else 'none'}",
    ]
    return "\n".join(lines)


def print_result(result: dict, as_json: bool):
    if as_json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return
    if "analysis" in result:
        a = Analysis(**result["analysis"])
        print(human_analysis(a))
        print(f"Fingerprint: {stable_hash(result['analysis'])}")
    if "changes" in result:
        print("\nChanges:")
        for path, status in result["changes"].items():
            print(f"  {status:10} {path}")
    if "findings" in result:
        print(f"\nAudit: {result['status']}")
        if not result["findings"]:
            print("  No findings.")
        for f in result["findings"]:
            print(f"  [{f['level']}] {f['message']}")
    if result.get("conflicts"):
        print("\nConflicts (preserved, not overwritten):")
        for p in result["conflicts"]:
            print(f"  {p}")
    if result.get("note"):
        print(f"\n{result['note']}")


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build a token-efficient Codex project harness")
    parser.add_argument("--version", action="version", version=VERSION)
    sub = parser.add_subparsers(dest="command", required=True)
    for cmd in ("analyze", "init", "update", "audit", "compact"):
        p = sub.add_parser(cmd)
        p.add_argument("--project", default=".", help="project/repository root")
        p.add_argument("--json", action="store_true", help="print JSON")
        if cmd in {"init", "update", "compact"}:
            p.add_argument("--dry-run", action="store_true", help="preview without writing")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    root = Path(args.project).expanduser().resolve()
    if not root.exists() or not root.is_dir():
        print(f"error: project directory does not exist: {root}", file=sys.stderr)
        return 2

    if args.command == "analyze":
        a = detect(root)
        result = asdict(a)
        if args.json:
            print(json.dumps(result, indent=2, ensure_ascii=False))
        else:
            print(human_analysis(a))
            print(f"Fingerprint: {stable_hash(result)}")
        return 0
    if args.command == "init":
        result = build(root, args.dry_run, update=False)
    elif args.command == "update":
        result = build(root, args.dry_run, update=True)
    elif args.command == "audit":
        result = audit(root)
    elif args.command == "compact":
        result = compact(root, args.dry_run)
    else:
        return 2

    print_result(result, args.json)
    return 1 if result.get("status") == "error" else 0



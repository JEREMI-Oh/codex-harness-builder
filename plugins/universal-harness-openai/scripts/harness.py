def load_manifest_targets(root: Path) -> list[str] | None:
    p = root / ".harness" / "manifest.json"
    if not p.exists():
        return None
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return None
    if data.get("_generated_by") != MANIFEST_GENERATOR:
        return None
    targets = data.get("targets")
    return targets if isinstance(targets, list) else None


def build_common(root: Path, analysis: Analysis, targets: list[str], dry_run: bool, changes: dict[str, str]) -> None:
    changes["AGENTS.md"] = write_managed(
        root / "AGENTS.md",
        universal_agents_block(analysis, targets),
        HTML_START,
        HTML_END,
        dry_run,
        legacy=(LEGACY_HTML_START, LEGACY_HTML_END),
    )

    for name, content in project_context(analysis).items():
        p = root / ".project-context" / name
        if p.exists():
            changes[rel(p, root)] = "preserved"
        else:
            changes[rel(p, root)] = write_owned(p, content, dry_run)

    if analysis.complexity == "LARGE":
        p = root / ".harness" / "PLANS.md"
        changes[rel(p, root)] = write_owned(p, plan_file(), dry_run) if not p.exists() else "preserved"
        keep = root / ".harness" / "plans" / ".gitkeep"
        if keep.exists():
            changes[rel(keep, root)] = "unchanged"
        else:
            if not dry_run:
                keep.parent.mkdir(parents=True, exist_ok=True)
                keep.write_text("", encoding="utf-8")
            changes[rel(keep, root)] = "created"


def build_codex(root: Path, analysis: Analysis, dry_run: bool, changes: dict[str, str]) -> None:
    cfg = root / ".codex" / "config.toml"
    changes[rel(cfg, root)] = write_managed(
        cfg,
        codex_agents_block(analysis),
        TOML_START,
        TOML_END,
        dry_run,
        legacy=(LEGACY_TOML_START, LEGACY_TOML_END),
    )
    for role in analysis.suggested_agents:
        p = root / ".codex" / "agents" / f"{role}.toml"
        changes[rel(p, root)] = write_owned(p, codex_role(role), dry_run)


def build_antigravity(root: Path, analysis: Analysis, dry_run: bool, changes: dict[str, str]) -> None:
    for role in analysis.suggested_agents:
        p = root / ".agents" / "agents" / f"{role}.md"
        changes[rel(p, root)] = write_owned(p, antigravity_role(role), dry_run)
    for kind in ("context-efficiency", "project-safety"):
        p = root / ".agents" / "rules" / f"harness-{kind}.md"
        changes[rel(p, root)] = write_owned(p, antigravity_rule(kind), dry_run)


def build_claude(root: Path, analysis: Analysis, dry_run: bool, changes: dict[str, str]) -> None:
    p = root / "CLAUDE.md"
    changes[rel(p, root)] = write_managed(p, claude_bridge_block(), CLAUDE_START, CLAUDE_END, dry_run)
    for role in analysis.suggested_agents:
        p = root / ".claude" / "agents" / f"{role}.md"
        changes[rel(p, root)] = write_owned(p, claude_role(role), dry_run)


def build(root: Path, dry_run: bool, target: str, mode: str = "init") -> dict:
    analysis = detect(root)
    manifest_targets = load_manifest_targets(root) if mode != "init" else None
    targets = resolve_targets(root, target, manifest_targets)
    changes: dict[str, str] = {}

    build_common(root, analysis, targets, dry_run, changes)
    if "codex" in targets:
        build_codex(root, analysis, dry_run, changes)
    if "antigravity" in targets:
        build_antigravity(root, analysis, dry_run, changes)
    if "claude-code" in targets:
        build_claude(root, analysis, dry_run, changes)

    manifest = {
        "_generated_by": MANIFEST_GENERATOR,
        "version": VERSION,
        "project": analysis.name,
        "complexity": analysis.complexity,
        "targets": targets,
        "suggested_agents": analysis.suggested_agents,
    }
    changes[".harness/manifest.json"] = write_json_owned(root / ".harness" / "manifest.json", manifest, dry_run)

    conflicts = [p for p, status in changes.items() if status == "conflict"]
    return {
        "version": VERSION,
        "mode": mode,
        "target_request": target,
        "targets": targets,
        "dry_run": dry_run,
        "analysis": asdict(analysis),
        "changes": changes,
        "conflicts": conflicts,
        "target_detection_note": (
            "No platform target was auto-detected; common project context was created only. Re-run with --target codex, antigravity, claude-code, or all."
            if target == "auto" and not targets else None
        ),
    }


def file_line_count(path: Path) -> int:
    try:
        return len(path.read_text(encoding="utf-8", errors="ignore").splitlines())
    except OSError:
        return 0


def audit(root: Path, target: str) -> dict:
    analysis = detect(root)
    manifest_targets = load_manifest_targets(root)
    targets = resolve_targets(root, target, manifest_targets)
    findings: list[dict[str, str]] = []

    def add(level: str, code: str, message: str):
        findings.append({"level": level, "code": code, "message": message})

    agents = root / "AGENTS.md"
    if not agents.exists():
        add("warning", "missing_agents", "AGENTS.md is missing.")
    else:
        lines = file_line_count(agents)
        if lines > 220:
            add("warning", "agents_bloat", f"AGENTS.md has {lines} lines; keep always-on instructions smaller.")
        text = agents.read_text(encoding="utf-8", errors="ignore")
        if text.count(HTML_START) > 1 or text.count(HTML_END) > 1:
            add("error", "duplicate_agents_blocks", "AGENTS.md contains duplicate universal harness markers.")
        if LEGACY_HTML_START in text:
            add("warning", "legacy_agents_block", "AGENTS.md still contains a legacy Codex harness block; run migrate/update.")

    memory = root / ".project-context" / "MEMORY.md"
    if memory.exists():
        lines = file_line_count(memory)
        if lines > 160:
            add("warning", "memory_bloat", f"MEMORY.md has {lines} lines; stable memory should remain intentionally small.")
        text = memory.read_text(encoding="utf-8", errors="ignore")
        for pat in SECRET_PATTERNS:
            if pat.search(text):
                add("error", "possible_secret", "MEMORY.md appears to contain secret-like material. Remove it and rotate any real credential.")
                break

    ctx = root / ".project-context"
    for name in ["PROJECT.md", "ARCHITECTURE.md", "DECISIONS.md", "MEMORY.md", "LESSONS.md", "TODO.md"]:
        if not (ctx / name).exists():
            add("info", "missing_context", f"Optional project context file is missing: .project-context/{name}")

    if "codex" in targets:
        cfg = root / ".codex" / "config.toml"
        if not cfg.exists():
            add("warning", "missing_codex_config", "Codex target selected but .codex/config.toml is missing.")
        for role in analysis.suggested_agents:
            p = root / ".codex" / "agents" / f"{role}.toml"
            if not p.exists():
                add("warning", "missing_codex_agent", f"Missing Codex role: {rel(p, root)}")

    if "antigravity" in targets:
        for role in analysis.suggested_agents:
            p = root / ".agents" / "agents" / f"{role}.md"
            if not p.exists():
                add("warning", "missing_antigravity_agent", f"Missing Antigravity role: {rel(p, root)}")
        for kind in ("context-efficiency", "project-safety"):
            p = root / ".agents" / "rules" / f"harness-{kind}.md"
            if not p.exists():
                add("warning", "missing_antigravity_rule", f"Missing Antigravity rule: {rel(p, root)}")

    if "claude-code" in targets:
        claude = root / "CLAUDE.md"
        if not claude.exists():
            add("warning", "missing_claude_md", "Claude Code target selected but CLAUDE.md is missing.")
        else:
            text = claude.read_text(encoding="utf-8", errors="ignore")
            if "@AGENTS.md" not in text:
                add("warning", "claude_missing_agents_import", "CLAUDE.md does not import @AGENTS.md; shared instructions may diverge.")
        for role in analysis.suggested_agents:
            p = root / ".claude" / "agents" / f"{role}.md"
            if not p.exists():
                add("warning", "missing_claude_agent", f"Missing Claude Code role: {rel(p, root)}")

    if analysis.complexity == "SMALL":
        for d in [root / ".codex" / "agents", root / ".agents" / "agents", root / ".claude" / "agents"]:
            if d.exists() and len(list(d.glob("*.md"))) + len(list(d.glob("*.toml"))) >= 4:
                add("warning", "too_many_agents", f"Small project has many custom roles in {rel(d, root)}; consider removing unused roles.")

    if (root / ".agent" / "PLANS.md").exists():
        add("info", "legacy_plan_location", "Legacy .agent/PLANS.md exists. V0.2 uses .harness/PLANS.md for platform-neutral plans.")

    severity = {"error": 3, "warning": 2, "info": 1}
    findings.sort(key=lambda x: severity[x["level"]], reverse=True)
    return {
        "version": VERSION,
        "targets": targets,
        "analysis": asdict(analysis),
        "status": "error" if any(f["level"] == "error" for f in findings) else "warning" if any(f["level"] == "warning" for f in findings) else "ok",
        "findings": findings,
    }


def normalize_text_file(path: Path, dry_run: bool) -> str:
    if not path.exists():
        return "missing"
    old = path.read_text(encoding="utf-8", errors="ignore")
    lines = [line.rstrip() for line in old.splitlines()]
    out: list[str] = []
    blanks = 0
    for line in lines:
        if line == "":
            blanks += 1
            if blanks > 2:
                continue
        else:
            blanks = 0
        out.append(line)
    new = "\n".join(out).rstrip() + "\n"
    if new == old:
        return "unchanged"
    if not dry_run:
        path.write_text(new, encoding="utf-8")
    return "updated"


def compact(root: Path, dry_run: bool, target: str) -> dict:
    targets = resolve_targets(root, target, load_manifest_targets(root))
    paths = [root / "AGENTS.md"]
    paths.extend((root / ".project-context").glob("*.md") if (root / ".project-context").exists() else [])
    if "codex" in targets:
        paths.append(root / ".codex" / "config.toml")
    if "antigravity" in targets:
        paths.extend((root / ".agents" / "rules").glob("harness-*.md") if (root / ".agents" / "rules").exists() else [])
    if "claude-code" in targets:
        paths.append(root / "CLAUDE.md")
    changes = {rel(p, root): normalize_text_file(p, dry_run) for p in paths}
    return {
        "version": VERSION,
        "targets": targets,
        "dry_run": dry_run,
        "changes": changes,
        "note": "Safe compaction normalized whitespace only. It did not summarize or delete project knowledge.",
    }


def stable_hash(data: object) -> str:
    raw = json.dumps(data, sort_keys=True, ensure_ascii=False).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:12]


def human_analysis(a: Analysis) -> str:
    return "\n".join([
        f"Project: {a.name}",
        f"Complexity: {a.complexity} (score={a.score})",
        f"Stack: {', '.join(a.stacks)}",
        f"Frameworks/tools: {', '.join(a.frameworks) if a.frameworks else 'none detected'}",
        f"Source files: {a.source_files}",
        f"Test-like files: {a.test_files}",
        f"Suggested agents: {', '.join(a.suggested_agents) if a.suggested_agents else 'none'}",
        f"Detected platforms: {', '.join(a.detected_platforms) if a.detected_platforms else 'none'}",
    ])


def print_result(result: dict, as_json: bool):
    if as_json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
        return
    if "analysis" in result:
        a = Analysis(**result["analysis"])
        print(human_analysis(a))
        print(f"Fingerprint: {stable_hash(result['analysis'])}")
    if "targets" in result:
        print(f"Targets: {', '.join(result['targets']) if result['targets'] else 'common only'}")
    if "changes" in result:
        print("\nChanges:")
        for path, status in result["changes"].items():
            print(f"  {status:10} {path}")
    if "findings" in result:
        print(f"\nAudit: {result['status']}")
        if not result["findings"]:
            print("  No findings.")
        for finding in result["findings"]:
            print(f"  [{finding['level']}] {finding['message']}")
    if result.get("conflicts"):
        print("\nConflicts (preserved, not overwritten):")
        for path in result["conflicts"]:
            print(f"  {path}")
    if result.get("target_detection_note"):
        print(f"\n{result['target_detection_note']}")
    if result.get("note"):
        print(f"\n{result['note']}")


def add_target_arg(parser: argparse.ArgumentParser):
    parser.add_argument(
        "--target",
        default="auto",
        choices=("auto", "common", "all", *TARGETS),
        help="platform adapter target; auto preserves prior manifest targets or detects local platform signals",
    )


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build a token-efficient universal coding-agent harness")
    parser.add_argument("--version", action="version", version=VERSION)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("analyze")
    p.add_argument("--project", default=".", help="project/repository root")
    p.add_argument("--json", action="store_true", help="print JSON")

    for cmd in ("init", "update", "migrate", "audit", "compact"):
        p = sub.add_parser(cmd)
        p.add_argument("--project", default=".", help="project/repository root")
        p.add_argument("--json", action="store_true", help="print JSON")
        add_target_arg(p)
        if cmd in {"init", "update", "migrate", "compact"}:
            p.add_argument("--dry-run", action="store_true", help="preview without writing")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    root = Path(args.project).expanduser().resolve()
    if not root.exists() or not root.is_dir():
        print(f"error: project directory does not exist: {root}", file=sys.stderr)
        return 2

    if args.command == "analyze":
        analysis = detect(root)
        result = asdict(analysis)
        if args.json:
            print(json.dumps(result, indent=2, ensure_ascii=False))
        else:
            print(human_analysis(analysis))
            print(f"Fingerprint: {stable_hash(result)}")
        return 0
    if args.command == "init":
        result = build(root, args.dry_run, args.target, mode="init")
    elif args.command == "update":
        result = build(root, args.dry_run, args.target, mode="update")
    elif args.command == "migrate":
        result = build(root, args.dry_run, args.target, mode="migrate")
    elif args.command == "audit":
        result = audit(root, args.target)
    elif args.command == "compact":
        result = compact(root, args.dry_run, args.target)
    else:
        return 2

    print_result(result, args.json)
    return 1 if result.get("status") == "error" else 0


if __name__ == "__main__":
    raise SystemExit(main())

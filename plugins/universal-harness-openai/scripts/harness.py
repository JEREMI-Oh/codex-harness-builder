@dataclass
class Analysis:
    project: str
    name: str
    stacks: list[str]
    frameworks: list[str]
    source_files: int
    test_files: int
    config_files: list[str]
    docs: list[str]
    monorepo_signals: list[str]
    complexity: str
    score: int
    suggested_agents: list[str]
    detected_platforms: list[str]


def iter_project_files(root: Path, max_files: int = 12000) -> Iterable[Path]:
    count = 0
    for current, dirs, files in os.walk(root):
        dirs[:] = [
            d for d in dirs
            if d not in IGNORE_DIRS and not d.startswith(".harness-cache")
        ]
        cur = Path(current)
        for name in files:
            if count >= max_files:
                return
            count += 1
            yield cur / name


def rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def detect_platforms(root: Path) -> list[str]:
    """Detect project/platform signals without assuming AGENTS.md means one host."""
    detected: list[str] = []

    if (root / ".codex").exists():
        detected.append("codex")

    antigravity_signals = [
        root / ".agents" / "agents",
        root / ".agents" / "rules",
        root / ".agents" / "skills",
        root / "GEMINI.md",
    ]
    if any(p.exists() for p in antigravity_signals):
        detected.append("antigravity")

    if (root / ".claude").exists() or (root / "CLAUDE.md").exists():
        detected.append("claude-code")

    if detected:
        return detected

    runtime_candidates: list[str] = []
    if shutil.which("codex"):
        runtime_candidates.append("codex")
    if shutil.which("agy") or shutil.which("antigravity"):
        runtime_candidates.append("antigravity")
    if shutil.which("claude"):
        runtime_candidates.append("claude-code")
    return runtime_candidates


def detect(root: Path) -> Analysis:
    files = list(iter_project_files(root))
    rels = {rel(p, root): p for p in files}
    names = set(rels)

    stacks: list[str] = []
    frameworks: list[str] = []
    config: list[str] = []
    docs: list[str] = []
    mono: list[str] = []

    def present(path: str) -> bool:
        return path in names

    manifests = {
        "package.json": "Node.js/JavaScript",
        "composer.json": "PHP",
        "pyproject.toml": "Python",
        "requirements.txt": "Python",
        "Pipfile": "Python",
        "go.mod": "Go",
        "Cargo.toml": "Rust",
        "pom.xml": "Java",
        "build.gradle": "Java/Kotlin",
        "build.gradle.kts": "Kotlin",
        "Gemfile": "Ruby",
        "pubspec.yaml": "Dart/Flutter",
    }
    for filename, stack in manifests.items():
        if present(filename):
            config.append(filename)
            if stack not in stacks:
                stacks.append(stack)

    if present("package.json"):
        try:
            pkg = json.loads(rels["package.json"].read_text(encoding="utf-8", errors="ignore"))
            deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
            candidates = {
                "react": "React", "next": "Next.js", "vue": "Vue", "nuxt": "Nuxt",
                "svelte": "Svelte", "express": "Express", "fastify": "Fastify",
                "@nestjs/core": "NestJS", "vite": "Vite",
            }
            for dep, label in candidates.items():
                if dep in deps and label not in frameworks:
                    frameworks.append(label)
            if "workspaces" in pkg:
                mono.append("package.json workspaces")
        except Exception:
            pass

    if present("composer.json"):
        try:
            comp = json.loads(rels["composer.json"].read_text(encoding="utf-8", errors="ignore"))
            req = {**comp.get("require", {}), **comp.get("require-dev", {})}
            for dep, label in {
                "laravel/framework": "Laravel", "symfony/framework-bundle": "Symfony"
            }.items():
                if dep in req and label not in frameworks:
                    frameworks.append(label)
        except Exception:
            pass

    for marker, label in {
        "manage.py": "Django",
        "artisan": "Laravel",
        "docker-compose.yml": "Docker Compose",
        "docker-compose.yaml": "Docker Compose",
        "compose.yml": "Docker Compose",
        "compose.yaml": "Docker Compose",
        "Dockerfile": "Docker",
    }.items():
        if present(marker):
            if marker not in config:
                config.append(marker)
            if label not in frameworks:
                frameworks.append(label)

    for path in names:
        lower = path.lower()
        base = Path(path).name.lower()
        if base in {"readme.md", "architecture.md", "contributing.md", "prd.md", "design.md"} or lower.startswith("docs/"):
            if len(docs) < 30:
                docs.append(path)
        if lower in {"pnpm-workspace.yaml", "lerna.json", "nx.json", "turbo.json"}:
            mono.append(path)
        if lower.endswith(".sln") and "C#/.NET" not in stacks:
            stacks.append("C#/.NET")

    source_files = 0
    test_files = 0
    ext_counts: dict[str, int] = {}
    for path in names:
        ext = Path(path).suffix.lower()
        if ext in SOURCE_EXTS:
            source_files += 1
            ext_counts[ext] = ext_counts.get(ext, 0) + 1
            if any(p.search(path) for p in TEST_PATTERNS):
                test_files += 1

    ext_stack = {
        ".py": "Python", ".php": "PHP", ".go": "Go", ".rs": "Rust", ".rb": "Ruby",
        ".java": "Java", ".kt": "Kotlin", ".kts": "Kotlin", ".cs": "C#/.NET",
        ".dart": "Dart/Flutter", ".swift": "Swift",
        ".js": "JavaScript", ".jsx": "JavaScript", ".ts": "TypeScript", ".tsx": "TypeScript",
    }
    for ext, count in sorted(ext_counts.items(), key=lambda x: x[1], reverse=True):
        label = ext_stack.get(ext)
        if label and count >= 2 and label not in stacks:
            stacks.append(label)

    score = 0
    score += min(source_files // 40, 8)
    score += max(0, len(stacks) - 1)
    score += min(len(frameworks) // 2, 3)
    score += 3 if mono else 0
    score += 2 if any(f == "Docker Compose" for f in frameworks) else 0
    score += 1 if test_files >= 10 else 0

    if source_files <= 30 and score <= 2:
        complexity = "SMALL"
        agents: list[str] = []
    elif source_files > 350 or score >= 9 or mono:
        complexity = "LARGE"
        agents = ["architect", "researcher", "developer", "tester", "reviewer"]
    else:
        complexity = "MEDIUM"
        agents = ["researcher", "developer", "tester", "reviewer"]

    return Analysis(
        project=str(root),
        name=root.name,
        stacks=stacks or ["Unknown/mixed"],
        frameworks=frameworks,
        source_files=source_files,
        test_files=test_files,
        config_files=sorted(config),
        docs=sorted(docs),
        monorepo_signals=sorted(set(mono)),
        complexity=complexity,
        score=score,
        suggested_agents=agents,
        detected_platforms=detect_platforms(root),
    )


def resolve_targets(root: Path, target: str, manifest_targets: list[str] | None = None) -> list[str]:
    if target == "all":
        return list(TARGETS)
    if target == "common":
        return []
    if target in TARGETS:
        return [target]
    if target != "auto":
        raise ValueError(f"unsupported target: {target}")

    if manifest_targets:
        valid = [t for t in manifest_targets if t in TARGETS]
        if valid:
            return valid
    return detect_platforms(root)


def replace_managed(text: str, block: str, start: str, end: str, legacy: tuple[str, str] | None = None) -> str:
    managed = f"{start}\n{block.rstrip()}\n{end}"
    if start in text and end in text:
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
        return pattern.sub(managed, text, count=1)
    if legacy and legacy[0] in text and legacy[1] in text:
        pattern = re.compile(re.escape(legacy[0]) + r".*?" + re.escape(legacy[1]), re.S)
        return pattern.sub(managed, text, count=1)
    base = text.rstrip()
    return (base + "\n\n" if base else "") + managed + "\n"


def write_managed(path: Path, block: str, start: str, end: str, dry_run: bool, legacy: tuple[str, str] | None = None) -> str:
    old = path.read_text(encoding="utf-8", errors="ignore") if path.exists() else ""
    new = replace_managed(old, block, start, end, legacy)
    if new == old:
        return "unchanged"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8")
    return "updated" if old else "created"


def is_owned_text(text: str) -> bool:
    return GENERATED_TEXT in text or LEGACY_GENERATED_TEXT in text


def write_owned(path: Path, content: str, dry_run: bool) -> str:
    if path.exists():
        old = path.read_text(encoding="utf-8", errors="ignore")
        if not is_owned_text(old):
            return "conflict"
        if old == content:
            return "unchanged"
        status = "updated"
    else:
        status = "created"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return status


def write_json_owned(path: Path, payload: dict, dry_run: bool) -> str:
    content = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    if path.exists():
        old = path.read_text(encoding="utf-8", errors="ignore")
        try:
            parsed = json.loads(old)
        except Exception:
            return "conflict"
        if parsed.get("_generated_by") != MANIFEST_GENERATOR:
            return "conflict"
        if old == content:
            return "unchanged"
        status = "updated"
    else:
        status = "created"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return status



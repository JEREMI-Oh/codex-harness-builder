def plan_file() -> str:
    return context_file(
        "Execution Plans",
        "Create a plan in `.harness/plans/` only for genuinely complex changes: cross-module work, migrations, contract changes, or risky multi-step implementations.\n\nA plan should contain: goal, current evidence, affected areas, steps, tests, migration/rollback notes, and completion criteria.\n",
    )


def codex_role(role: str) -> str:
    effort, _, instructions = role_spec(role)
    return (
        f"# {GENERATED_TEXT} v{VERSION}\n"
        f"model_reasoning_effort = \"{effort}\"\n"
        "developer_instructions = \"\"\"\n"
        f"{instructions}\n"
        "\"\"\"\n"
    )


def codex_agents_block(analysis: Analysis) -> str:
    if not analysis.suggested_agents:
        return "# Small project: custom subagents intentionally omitted to reduce context and orchestration overhead."
    lines = ["[agents]", "enabled = true", ""]
    for role in analysis.suggested_agents:
        _, description, _ = role_spec(role)
        lines += [
            f"[agents.{role}]",
            f'description = "{description}"',
            f'config_file = "agents/{role}.toml"',
            "",
        ]
    return "\n".join(lines).rstrip()



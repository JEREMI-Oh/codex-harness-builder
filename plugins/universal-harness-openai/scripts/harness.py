def universal_agents_block(analysis: Analysis, targets: list[str]) -> str:
    stack = ", ".join(analysis.stacks)
    frameworks = ", ".join(analysis.frameworks) if analysis.frameworks else "none detected"
    target_text = ", ".join(targets) if targets else "common context only"
    return f"""# Universal project harness

Project profile: **{analysis.complexity}** | Stack: {stack} | Frameworks: {frameworks} | Targets: {target_text}

## Working rules
- Start from the user's requested scope. Locate relevant files before reading broad directories.
- Do not read the full repository, long PRDs, or all project-context files by default.
- For simple dependent work, stay in the main agent. Use subagents only when specialization, isolation, or parallel work has clear value.
- Give each subagent only the files, requirements, constraints, and acceptance criteria it needs.
- Preserve existing APIs, schemas, dependencies, behavior, and conventions unless the task explicitly requires changing them.
- Avoid unrelated refactors, formatting churn, dependency changes, and speculative cleanup.
- Run the narrowest meaningful tests first; expand only when results or risk justify it.
- Keep completion reports concise: changed files, key change, tests, and remaining risk.

## Durable project knowledge
- `.project-context/PROJECT.md`: stable project facts and entry points.
- `.project-context/ARCHITECTURE.md`: current architecture, not future wishes.
- `.project-context/DECISIONS.md`: lasting design decisions with rationale.
- `.project-context/MEMORY.md`: only small, stable facts that materially help future work.
- `.project-context/LESSONS.md`: reusable failure/solution patterns.
- `.project-context/TODO.md`: current project work, not chat history.
- Read only the project-context file relevant to the current task. Never load all of them by default.
- Never store passwords, private keys, API keys, access tokens, credentials, or other secrets in these files.

## Complexity policy
- SIMPLE: solve directly; no durable plan and usually no subagents.
- MEDIUM: targeted research -> implementation -> focused tests; reviewer only when risk warrants it.
- COMPLEX: architecture/plan -> targeted research -> implementation -> tests -> review. Use `.harness/plans/` only for genuinely cross-cutting work.
"""


def context_file(title: str, body: str) -> str:
    return f"<!-- {GENERATED_TEXT} v{VERSION} -->\n\n# {title}\n\n{body.rstrip()}\n"


